# Textos de FocusWShell en español (Strings.resx) e inglés (Strings.en.resx).
#
#   powershell -File build\textos.ps1
#       Regenera src\FocusWShell.App\Strings.Designer.cs a partir de Strings.resx. Hay que hacerlo tras
#       editar a mano el .resx de la app: el compilador de XAML necesita la clase antes de que MSBuild genere
#       recursos, así que vive junto al .resx (la del núcleo la genera MSBuild sola).
#
#   powershell -File build\textos.ps1 -Clave Deck_Hola -Es "Hola, {0}" -En "Hello, {0}" [-Proyecto Core]
#       Añade o cambia un texto en los dos idiomas (por defecto en la app) y regenera la clase.
#       En el código: Strings.Deck_Hola, o Core.Text.F(Strings.Deck_Hola, nombre) si tiene huecos.
#
# TranslationTests comprueba que los dos .resx tienen las mismas claves y los mismos huecos {0}, {1}…
param(
    [string]$Clave,
    [string]$Es,
    [string]$En,
    [ValidateSet('App', 'Core')][string]$Proyecto = 'App'
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$utf8Bom = New-Object System.Text.UTF8Encoding $true

function Escape([string]$s) { $s.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;') }

function Read-Resx([string]$path) {
    $map = New-Object 'System.Collections.Generic.Dictionary[string,string]'
    if (Test-Path $path) {
        [xml]$doc = [System.IO.File]::ReadAllText($path)
        foreach ($d in $doc.root.data) { $map[$d.name] = [string]$d.value }
    }
    return , $map
}

function Sorted($map) {
    $keys = [string[]]@($map.Keys)
    [Array]::Sort($keys, [StringComparer]::Ordinal)
    return , $keys
}

function Write-Resx([string]$path, $map) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<root>`n")
    [void]$sb.Append("  <resheader name=`"resmimetype`"><value>text/microsoft-resx</value></resheader>`n")
    [void]$sb.Append("  <resheader name=`"version`"><value>2.0</value></resheader>`n")
    [void]$sb.Append("  <resheader name=`"reader`"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>`n")
    [void]$sb.Append("  <resheader name=`"writer`"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>`n")
    foreach ($k in (Sorted $map)) {
        [void]$sb.Append("  <data name=`"$k`" xml:space=`"preserve`"><value>$(Escape $map[$k])</value></data>`n")
    }
    [void]$sb.Append("</root>`n")
    [System.IO.File]::WriteAllText($path, $sb.ToString(), $utf8Bom)
}

# Añadir o cambiar un texto.
if ($Clave) {
    if ($Clave -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw "Clave no válida: $Clave (letras, números y _)." }
    if (-not $Es -or -not $En) { throw 'Hacen falta -Es y -En.' }
    $folder = Join-Path $repo "src\FocusWShell.$Proyecto"
    foreach ($pair in @(@('Strings.resx', $Es), @('Strings.en.resx', $En))) {
        $path = Join-Path $folder $pair[0]
        $map = Read-Resx $path
        $map[$Clave] = $pair[1]
        Write-Resx $path $map
    }
    Write-Host "Texto $Clave en FocusWShell.$Proyecto (es / en)."
}

# Regenerar la clase de la app.
$appFolder = Join-Path $repo 'src\FocusWShell.App'
$texts = Read-Resx (Join-Path $appFolder 'Strings.resx')
$lines = New-Object System.Collections.Generic.List[string]
$lines.AddRange([string[]]@(
    '// <auto-generated>',
    '// Generado a partir de Strings.resx por build\textos.ps1. No editar a mano.',
    '// </auto-generated>',
    '#nullable enable',
    'namespace FocusWShell.App;',
    '',
    '/// <summary>Textos de la interfaz (Strings.resx en español, Strings.en.resx en inglés).</summary>',
    'public static class Strings',
    '{',
    '    private static System.Resources.ResourceManager? _manager;',
    '',
    '    public static System.Resources.ResourceManager ResourceManager =>',
    '        _manager ??= new System.Resources.ResourceManager("FocusWShell.App.Strings", typeof(Strings).Assembly);',
    '',
    '    /// <summary>Cultura de los textos; <c>null</c>: la de la interfaz.</summary>',
    '    public static System.Globalization.CultureInfo? Culture { get; set; }'))
foreach ($k in (Sorted $texts)) {
    $v = $texts[$k]
    $summary = (Escape $v.Substring(0, [Math]::Min(80, $v.Length))).Replace("`n", ' ')
    $lines.Add('')
    $lines.Add("    /// <summary>$summary</summary>")
    $lines.Add("    public static string $k => ResourceManager.GetString(`"$k`", Culture)!;")
}
$lines.Add('}')
[System.IO.File]::WriteAllText((Join-Path $appFolder 'Strings.Designer.cs'), ([string]::Join("`n", $lines) + "`n"), $utf8Bom)
Write-Host "Strings.Designer.cs: $($texts.Count) textos."
